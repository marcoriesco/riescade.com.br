import dotenv from 'dotenv';
import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {createClient} from '@supabase/supabase-js';
dotenv.config({path:'.env.local',quiet:true});
const folder='D:/Downloads/tmp/RIESCADE/arts/instagram/reels/01_sua-infancia-tem-um-novo-play';
const id='c956ae2f-34e8-45b2-9469-734c5990dcef';
const db=createClient(process.env.NEXT_PUBLIC_SUPABASE_URL,process.env.SUPABASE_SERVICE_ROLE_KEY,{auth:{persistSession:false,autoRefreshToken:false}});
const {data,error}=await db.from('instagram_posts').select('media_path,status').eq('id',id).single();
if(error)throw new Error('Could not verify media record');
const url=db.storage.from('instagram-media').getPublicUrl(data.media_path).data.publicUrl;
const response=await fetch(url,{signal:AbortSignal.timeout(20000)});
if(!response.ok)throw new Error(`Media unavailable: ${response.status}`);
const remote=Buffer.from(await response.arrayBuffer());
const local=await readFile(folder+'/riescade-reel-01_1080x1920.mp4');
const digest=b=>createHash('sha256').update(b).digest('hex');
if(digest(remote)!==digest(local))throw new Error('Uploaded video differs from approved file');
const result={accessible:true,contentType:response.headers.get('content-type'),bytes:remote.length,sha256:digest(remote),matchesApprovedFile:true,status:data.status};
await writeFile(folder+'/media-verification.json',JSON.stringify(result,null,2));console.log(JSON.stringify(result));
